#pragma once

// ===================================================================================
// 引脚定义
// ===================================================================================
// 仅用于满足 SDK 自带 i2c.c / oled.c 的编译,本工程不会调用它们。
// P3.0 本工程未使用,借来占位。
#define PIN_SDA             P30
#define PIN_SCL             P30

// 本工程实际使用的引脚见 keypad.h / uart.h:
//   按键 : P1.0..P1.7, P3.2, P3.3, P3.4, P3.5  (内部上拉, 按下接地)
//   串口 : P3.1 = TXD (UART0, 单向发送给上级单片机)

// ===================================================================================
// USB 设备描述符
// -----------------------------------------------------------------------------------
// ★ 重要: 不要用 0x045E/0x028E(微软 Xbox 360 手柄)!!
//   实测(2026-10-12, Windows 11): 一填这个 ID，Windows 的 INF 会把它直接匹配给
//   XInput 驱动(XnaComposite / xusb22)，走的是“真·XInput 协议”(厂商自定义接口 +
//   20 字节报文 + 握手包)。而本固件是标准的 HID 类手柄，协议对不上 ->
//   驱动占着设备却读不到数据:
//       XInputGetState() -> 1163 (ERROR_DEVICE_NOT_CONNECTED)
//       设备管理器里也不会出现 “符合 HID 标准的游戏控制器”
//   结果就是: 游戏里完全用不了。
//
//   正确做法: 用一个**普通/中性**的 VID+PID，让 Windows 加载通用 HID 驱动，
//   出现 “符合 HID 标准的游戏控制器”，joy.cpl 可测，支持 DInput 的游戏/模拟器
//   (SDL2) 能直接用。
//   默认用 0x0079/0x0006 —— 最经典的“通用 PC 手柄”ID，老游戏/模拟器兼容最好。
//   想换别的也可以，例如开源项目专用的 pid.codes VID:
//       #define USB_VENDOR_ID  0x1209
//       #define USB_PRODUCT_ID 0x0001
//
//   若某些游戏“只认 XInput”: 属 PC 侧问题，不该在芯片里解决。
//   PC 上装开源的 ViGEmBus，用软件把本 HID 手柄桥接成虚拟 XInput 手柄即可，
//   设备端零改动。( github.com/nefarius/ViGEmBus )
// ===================================================================================
#define USB_VENDOR_ID       0x0079      // 通用手柄 VID(仿 DragonRise)
#define USB_PRODUCT_ID      0x0006      // 通用手柄 PID
#define USB_DEVICE_VERSION  0x0100      // v1.0 (BCD)

#define USB_MAX_POWER_mA    100         // 最大取电电流 (mA)

// ===================================================================================
// USB 字符串描述符(必须写成 "逗号分隔的字符列表")
// ===================================================================================
#define MANUFACTURER_STR    'C','H','5','5','2','T'
#define PRODUCT_STR         'X','b','o','x',' ','3','6','0',' ','G','a','m','e','p','a','d'
#define SERIAL_STR          'C','H','5','5','2','T','-','G','P','0','0','0','1'
#define INTERFACE_STR       'G','a','m','e','p','a','d'
