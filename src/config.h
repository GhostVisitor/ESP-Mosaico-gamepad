// 说明:本文件同时被 USB 驱动(usb_descr.c)和 SDK 自带的 i2c.c / oled.c 包含,
//       所以除 USB 参数外,仍需保留 PIN_SDA / PIN_SCL 两个宏(本工程用不到 I2C/OLED,
//       但 SDK 的构建脚本会无条件编译 template/src/i2c.c 与 oled.c)。
