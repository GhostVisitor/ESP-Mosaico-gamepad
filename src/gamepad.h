// 方向键是否同时驱动左摇杆 X/Y(满偏)。
//   1 = 同时驱动(既兼容"读方向键"的游戏,也兼容"读摇杆"的游戏)
//   0 = 只当苦力帽/方向键,左摇杆始终居中
#define GP_DPAD_ALSO_STICK     1

// 手柄报告长度(字节)
#define GP_REPORT_LEN          7

void GAMEPAD_init(void);

// 根据键位掩码更新并(在需要时)发送手柄报告
void GAMEPAD_update(uint16_t keys);
