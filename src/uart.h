// ===================================================================================
// UART0 单向发送 —— 把按键状态上报给上级单片机
// -----------------------------------------------------------------------------------
// 引脚: P3.1 = TXD, P3.0 = RXD (UART0 默认引脚)
// 参数: 19200 bps, 8 数据位, 无校验, 1 停止位
//
// 关于 RXD: 本工程只需要把按键状态发给上级单片机,属于**单向发送**,
//   因此 REN=0 不使能接收,P3.0 保持空闲(不接线也不影响发送)。
//   以后若要接收,把 SCON 的 REN 置 1、打开 ES 即可,P3.0 已预留。
//
// 帧格式(二进制, 共 5 字节):
//   0        : 0xA5   帧头1
//   1        : 0x5A   帧头2
//   2        : keys 低 8 位
//   3        : keys 高 4 位(只用 bit0..bit3)
//   4        : 前 4 字节异或校验
//   keys 的 bit n = KEY_(n+1) 按下(与 keypad.h 的键位掩码一致)
// ===================================================================================

#pragma once
#include <stdint.h>

#define UART_FRAME_HEAD0    0xA5
#define UART_FRAME_HEAD1    0x5A
#define UART_FRAME_SIZE     5

// 初始化 UART0(P3.1 = TXD, 19200 8N1)
void UART_init(void);

// 发送单个字节(阻塞直到发完)
void UART_putc(char c);

// 按上面的帧格式发送一次键位状态
void UART_sendState(uint16_t keys);
